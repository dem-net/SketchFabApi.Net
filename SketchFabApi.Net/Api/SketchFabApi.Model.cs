using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Net.Http;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Runtime.CompilerServices;
using System.Text.Json;
using System.Text.Json.Serialization.Metadata;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.Extensions.Logging;

namespace Sketchfab;

public partial class SketchfabApi
{
    private const int UploadBufferSize = 81920;

    /// <summary>
    /// Uploads a model file. The file is streamed from disk.
    /// A non-success status code doesn't throw: it is returned in <see cref="SketchfabUploadResponse.StatusCode"/>.
    /// </summary>
    public async Task<SketchfabUploadResponse> UploadModelAsync(UploadModelRequest request, string sketchFabToken, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        ArgumentException.ThrowIfNullOrWhiteSpace(request.FilePath);
        if (!File.Exists(request.FilePath))
        {
            throw new FileNotFoundException($"File [{request.FilePath}] not found.", request.FilePath);
        }

        _logger.LogInformation("Uploading model {FilePath}", request.FilePath);

        var fileStream = new FileStream(request.FilePath, FileMode.Open, FileAccess.Read, FileShare.Read, UploadBufferSize,
            FileOptions.Asynchronous | FileOptions.SequentialScan);
        using var form = new MultipartFormDataContent();
        var fileContent = new StreamContent(fileStream, UploadBufferSize); // disposed with the form
        fileContent.Headers.ContentType = new MediaTypeHeaderValue("application/octet-stream");
        form.Add(fileContent, "modelFile", Path.GetFileName(request.FilePath));
        if (!string.IsNullOrWhiteSpace(request.Source))
        {
            form.Add(new StringContent(request.Source), "source");
        }
        else
        {
            _logger.LogWarning("Sketchfab upload has no source configured. It's better to set one to uniquely identify all the models generated by the exporter, see https://Sketchfab.com/developers/guidelines#source");
        }

        AddCommonModelFields(form, request);

        using var httpRequest = CreateRequest(HttpMethod.Post, $"{SketchfabApiUrl}/models", sketchFabToken, request.TokenType);
        httpRequest.Content = form;

        HttpResponseMessage response;
        try
        {
            response = await CreateClient().SendAsync(httpRequest, HttpCompletionOption.ResponseHeadersRead, cancellationToken).ConfigureAwait(false);
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            _logger.LogError(ex, "Sketchfab upload failed");
            throw;
        }

        using (response)
        {
            _logger.LogInformation("Sketchfab {Operation} responded {StatusCode}", nameof(UploadModelAsync), response.StatusCode);
            var sfResponse = new SketchfabUploadResponse(response.StatusCode, response.ReasonPhrase ?? string.Empty);
            if (!response.IsSuccessStatusCode)
            {
                await LogErrorResponseAsync(response, nameof(UploadModelAsync), cancellationToken).ConfigureAwait(false);
                return sfResponse;
            }

            string? uid = response.Headers.TryGetValues("Location", out var location) ? location.FirstOrDefault() : null;
            if (string.IsNullOrEmpty(uid))
            {
                // The response body also holds the uid: {"uid": "...", "uri": "..."}
                var body = await response.Content.ReadFromJsonAsync(SketchfabJsonContext.Default.UploadResult, cancellationToken).ConfigureAwait(false);
                uid = body?.uid;
            }
            sfResponse.ModelId = uid;
            request.ModelId = uid;
            _logger.LogInformation("Uploading is complete. Model uuid is {ModelId}", uid);
            return sfResponse;
        }
    }

    public async Task UpdateModelAsync(string modelId, UpdateModelRequest request, string sketchFabToken, TokenType tokenType, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(modelId);
        ArgumentNullException.ThrowIfNull(request);
        _logger.LogInformation("Updating model {ModelId}", modelId);

        using var form = new MultipartFormDataContent();
        AddCommonModelFields(form, request);
        using var httpRequest = CreateRequest(HttpMethod.Patch, $"{SketchfabApiUrl}/models/{modelId}", sketchFabToken, tokenType);
        httpRequest.Content = form;

        await SendAsync(httpRequest, nameof(UpdateModelAsync), cancellationToken).ConfigureAwait(false);
    }

    public async Task<Model> GetModelAsync(string modelId, string sketchFabToken, TokenType tokenType, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(modelId);
        _logger.LogInformation("Get model {ModelId}", modelId);

        using var request = CreateRequest(HttpMethod.Get, $"{SketchfabApiUrl}/models/{modelId}", sketchFabToken, tokenType);
        request.Headers.CacheControl = new CacheControlHeaderValue { NoCache = true };
        return await SendForJsonAsync(request, SketchfabJsonContext.Default.Model, nameof(GetModelAsync), cancellationToken).ConfigureAwait(false);
    }

    public IAsyncEnumerable<Model> GetMyModelsAsync(string sketchFabToken, TokenType tokenType, CancellationToken cancellationToken = default)
    {
        _logger.LogInformation("Get my models");
        return GetPagedResultAsync($"{SketchfabApiUrl}/me/models", sketchFabToken, tokenType, SketchfabJsonContext.Default.PagedResultModel, cancellationToken);
    }

    /// <summary>
    /// Follows the <c>next</c> links, with a new request for each page.
    /// </summary>
    private async IAsyncEnumerable<T> GetPagedResultAsync<T>(string url, string token, TokenType tokenType, JsonTypeInfo<PagedResult<T>> typeInfo,
        [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        int numResults = 0, numPages = 0;
        string? next = url;
        while (next is not null)
        {
            PagedResult<T> page;
            using (var request = CreateRequest(HttpMethod.Get, next, token, tokenType))
            {
                page = await SendForJsonAsync(request, typeInfo, $"{nameof(GetPagedResultAsync)}<{typeof(T).Name}>", cancellationToken).ConfigureAwait(false);
            }
            numPages++;
            foreach (var item in page.results ?? [])
            {
                numResults++;
                yield return item;
            }
            next = page.next;
        }

        _logger.LogInformation("{Operation}<{Type}> returned {NumResults} result(s) in {NumPages} page(s)", nameof(GetPagedResultAsync), typeof(T).Name, numResults, numPages);
    }

    public async Task<bool> IsReadyAsync(string modelId, string token, CancellationToken cancellationToken = default)
    {
        var model = await GetModelAsync(modelId, token, TokenType.Token, cancellationToken).ConfigureAwait(false);
        return model.IsReady();
    }
}
